#!/usr/bin/env bash
# Resolve the exact upstream commits to build a given Proxmox Backup Server release from,
# and write them to versions.env.
#
#   scripts/pin.sh            # latest vX.Y.Z tag of proxmox-backup
#   scripts/pin.sh 4.2.8      # a specific release
#
# Rules:
#   - proxmox-backup:            the release tag itself
#   - proxmox, pxar, pathpatterns, proxmox-fuse (Rust crates PBS depends on via git):
#                                last master commit at or before the release commit
#   - proxmox-termproxy, proxmox-mini-journalreader (arch-specific runtime deps):
#                                the commit whose debian/changelog introduced the version
#                                that Proxmox currently ships in pbs-no-subscription
set -euo pipefail
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=advice.detachedHead GIT_CONFIG_VALUE_0=false

GIT=${PROXMOX_GIT:-https://git.proxmox.com/git}
REPO_INDEX=${PROXMOX_REPO_INDEX:-http://download.proxmox.com/debian/pbs/dists/trixie/pbs-no-subscription/binary-amd64/Packages.gz}
OUT=${OUT:-versions.env}
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

latest_tag() {
  git ls-remote --tags --refs "$GIT/proxmox-backup.git" 'v*' |
    sed -n 's|.*refs/tags/v\([0-9]*\.[0-9]*\.[0-9]*\)$|\1|p' | sort -V | tail -1
}

PBS_VERSION=${1:-$(latest_tag)}
[[ "$PBS_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "bad version: $PBS_VERSION" >&2; exit 1; }

git clone -q --depth 1 --branch "v$PBS_VERSION" "$GIT/proxmox-backup.git" "$WORK/proxmox-backup"
PBS_COMMIT=$(git -C "$WORK/proxmox-backup" rev-parse HEAD)
PBS_DATE=$(git -C "$WORK/proxmox-backup" log -1 --format=%cI)
grep -q "^version = \"$PBS_VERSION\"" "$WORK/proxmox-backup/Cargo.toml" ||
  { echo "Cargo.toml version does not match tag v$PBS_VERSION" >&2; exit 1; }

# last commit on the default branch at or before the PBS release
commit_before() {
  local repo=$1
  git clone -q --bare --filter=blob:none "$GIT/$repo.git" "$WORK/$repo.git" 2>/dev/null ||
    git clone -q --bare "$GIT/$repo.git" "$WORK/$repo.git"
  git -C "$WORK/$repo.git" rev-list -1 --before="$PBS_DATE" HEAD
}

# commit whose changelog first introduced "<package> (<version>)"
commit_for_version() {
  local repo=$1 changelog=$2 package=$3 version=$4
  [[ -d "$WORK/$repo" ]] || git clone -q "$GIT/$repo.git" "$WORK/$repo"
  local c
  c=$(git -C "$WORK/$repo" log -1 --format=%H -S"$package ($version)" -- "$changelog")
  [[ -n "$c" ]] || { echo "no commit for $package $version in $repo" >&2; exit 1; }
  echo "$c"
}

shipped_version() {
  curl -fsSL "$REPO_INDEX" | gunzip |
    awk -v p="$1" 'BEGIN{RS="";FS="\n"} {pk="";v=""; for(i=1;i<=NF;i++){if($i~/^Package: /)pk=substr($i,10); if($i~/^Version: /)v=substr($i,10)} if(pk==p) print v}' |
    sort -V | tail -1
}

TERMPROXY_VERSION=$(shipped_version proxmox-termproxy)
JOURNALREADER_VERSION=$(shipped_version proxmox-mini-journalreader)

cat > "$OUT" <<EOF
# Generated by scripts/pin.sh — do not edit by hand.
PBS_VERSION=$PBS_VERSION
PBS_COMMIT=$PBS_COMMIT
PBS_DATE=$PBS_DATE
PROXMOX_COMMIT=$(commit_before proxmox)
PXAR_COMMIT=$(commit_before pxar)
PATHPATTERNS_COMMIT=$(commit_before pathpatterns)
PROXMOX_FUSE_COMMIT=$(commit_before proxmox-fuse)
TERMPROXY_VERSION=$TERMPROXY_VERSION
TERMPROXY_COMMIT=$(commit_for_version pve-xtermjs termproxy/debian/changelog proxmox-termproxy "$TERMPROXY_VERSION")
JOURNALREADER_VERSION=$JOURNALREADER_VERSION
JOURNALREADER_COMMIT=$(commit_for_version proxmox-mini-journalreader debian/changelog proxmox-mini-journalreader "$JOURNALREADER_VERSION")
EOF
cat "$OUT"
